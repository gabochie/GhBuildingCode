#!/usr/bin/env node
/**
 * GHBC Academy content builder.
 *
 * Turns the GS 1207:2018 corpus (ghbc-corpus) into idempotent D1 SQL for the
 * academy tables (migration 0004_academy.sql):
 *   - certifications / academy_courses / academy_lessons  (from docs/academy-curriculum.v1.json)
 *   - academy_questions                                    (deterministically from requirements + definitions)
 *
 *   node scripts/build-academy.mjs            # writes migrations/d1-seed/academy.sql
 *   node scripts/build-academy.mjs --check    # parse + count only, no file written
 *
 * Env:
 *   BCGH_CORPUS    corpus root     (default: C:\Users\user\Desktop\GABOCHIE CORP\GHANA BUILDING CODE OPERATIONS\ghbc-corpus)
 *   ACADEMY_CURRICULUM  curriculum json (default: <repo>/data/academy-curriculum.v1.json)
 *
 * Design rules (see docs/ACADEMY_PLAN.md §4/§9):
 *   - No invented code text. Question distractors reuse real corpus values.
 *   - Only `verification_status = extracted` AND confidence >= 0.9 are exam-eligible.
 *   - Every question stores clause_id / requirement_id / page / content_hash.
 */
import fs from "node:fs";
import path from "node:path";
import { createHash } from "node:crypto";
import { fileURLToPath } from "node:url";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const root = path.resolve(__dirname, "..");

const CORPUS =
  process.env.BCGH_CORPUS ||
  "C:\\Users\\user\\Desktop\\GABOCHIE CORP\\GHANA BUILDING CODE OPERATIONS\\ghbc-corpus";
const CURRICULUM_PATH =
  process.env.ACADEMY_CURRICULUM || path.join(root, "data", "academy-curriculum.v1.json");
const OUT_PATH = path.join(root, "migrations", "d1-seed", "academy.sql");
const CHECK_ONLY = process.argv.includes("--check");

const P = (name) => path.join(CORPUS, name);
const log = (msg) => console.log(`[academy] ${msg}`);

if (!fs.existsSync(CORPUS)) {
  console.error(`[academy] corpus not found: ${CORPUS}`);
  process.exit(1);
}

// --- SQL helpers (single-quote escaping for SQLite/D1) -----------------------
const q = (v) => (v === null || v === undefined ? "NULL" : `'${String(v).replace(/'/g, "''")}'`);
const n = (v) => (v === null || v === undefined || Number.isNaN(Number(v)) ? "NULL" : String(Number(v)));
const id = (prefix, ...parts) =>
  `${prefix}-${createHash("sha1").update(parts.join("|")).digest("hex").slice(0, 16)}`;

// --- load corpus -------------------------------------------------------------
log(`corpus: ${CORPUS}`);
const hierarchy = JSON.parse(fs.readFileSync(P("json/ghana-building-code.json"), "utf8"));
const curriculum = JSON.parse(fs.readFileSync(CURRICULUM_PATH, "utf8"));
log(`hierarchy: ${hierarchy.parts.length} parts, ${hierarchy.clauses.length} clauses`);

// clause index: "PART-01:SEC-1.1" -> clause rows
const clausesBySection = new Map();
for (const c of hierarchy.clauses) {
  const key = `${c.part}:${c.section}`;
  if (!clausesBySection.has(key)) clausesBySection.set(key, []);
  clausesBySection.get(key).push(c);
}

// --- stream requirements.jsonl ----------------------------------------------
function readJsonl(file) {
  const rows = [];
  const fd = fs.openSync(file, "r");
  let buf = "";
  const sz = 4 * 1024 * 1024;
  const rd = Buffer.alloc(sz);
  let read;
  while ((read = fs.readSync(fd, rd, 0, sz, null)) > 0) {
    buf += rd.toString("utf8", 0, read);
    let i;
    while ((i = buf.indexOf("\n")) !== -1) {
      const line = buf.slice(0, i).trim();
      buf = buf.slice(i + 1);
      if (line) rows.push(JSON.parse(line));
    }
  }
  if (buf.trim()) rows.push(JSON.parse(buf.trim()));
  fs.closeSync(fd);
  return rows;
}

// --- lesson body from markdown (per section) ---------------------------------
function markdownForPart(partNo) {
  const f = P(`markdown/part-${String(partNo).padStart(2, "0")}.md`);
  return fs.existsSync(f) ? fs.readFileSync(f, "utf8") : null;
}

// Extract a section's markdown slice: from "## <section>" up to the next "## ".
function sectionSlice(md, sectionNo) {
  if (!md) return null;
  const esc = sectionNo.replace(/[.*+?^${}()|[\]\\]/g, "\\$&");
  const re = new RegExp(`^##\\s+${esc}\\b.*$`, "m");
  const m = md.match(re);
  if (!m) return null;
  const start = m.index;
  const rest = md.slice(start + m[0].length);
  const nextIdx = rest.search(/^##\s+/m);
  const body = (nextIdx === -1 ? rest : rest.slice(0, nextIdx)).trim();
  return body.length > 20 ? body : null;
}

// =============================================================================
// 1. Catalog + lessons
// =============================================================================
const catalogSql = [];
const lessonRows = []; // { slug, part, section, clauseIds, pages }

catalogSql.push("-- certifications, courses, lessons — generated by scripts/build-academy.mjs");

for (const cert of curriculum.certifications) {
  const certId = id("cert", cert.slug);
  catalogSql.push(
    `INSERT OR REPLACE INTO certifications (id, slug, title, level, description, price_ghs_minor, is_free, prerequisite_slug, exam_questions, exam_minutes, exam_pass_percent, sort_order) VALUES (` +
      [
        q(certId),
        q(cert.slug),
        q(cert.title),
        q(cert.level),
        q(cert.description || null),
        q(String(cert.priceGhsMinor ?? "0")),
        cert.isFree ? 1 : 0,
        q(cert.prerequisite || null),
        n(cert.exam?.questions),
        n(cert.exam?.minutes),
        n(cert.exam?.passPercent ?? 80),
        n(curriculum.certifications.indexOf(cert))
      ].join(", ") +
      ");"
  );

  let courseOrder = 0;
  for (const course of cert.courses) {
    const courseId = id("course", cert.slug, course.slug);
    catalogSql.push(
      `INSERT OR REPLACE INTO academy_courses (id, certification_id, slug, title, summary, part_no, sort_order) VALUES (` +
        [q(courseId), q(certId), q(course.slug), q(course.title), q(course.summary || null), n(course.part), n(courseOrder++)].join(", ") +
        ");"
    );

    // Lessons: either explicitly declared, or synthesized from the part's sections.
    let lessons = course.lessons;
    if (!lessons || !lessons.length) {
      const partSections = (hierarchy.parts.find((p) => p.part === course.part)?.sections) || [];
      lessons = partSections.slice(0, 12).map((s, idx) => ({
        slug: `${course.slug}-l${idx + 1}`,
        title: String(s.title || `Section ${s.number}`).replace(/^[\d.]+\s*/, "").slice(0, 120) || `Section ${s.number}`,
        section: String(s.number)
      }));
    }

    let lessonOrder = 0;
    for (const lesson of lessons) {
      const lessonId = id("lesson", cert.slug, course.slug, lesson.slug);
      const md = markdownForPart(course.part);
      const body = sectionSlice(md, lesson.section) || null;
      const clauseRows = clausesBySection.get(`${course.part}:${lesson.section}`) || [];
      const clauseIds = clauseRows.map((c) => c.id);
      const pages = [
        ...new Set(clauseRows.map((c) => c.source?.page_start).filter((p) => p != null))
      ].sort((a, b) => a - b);

      lessonRows.push({
        slug: lesson.slug,
        part: course.part,
        section: lesson.section,
        courseSlug: course.slug,
        clauseIds,
        pages
      });

      catalogSql.push(
        `INSERT OR REPLACE INTO academy_lessons (id, course_id, slug, title, body_md, est_minutes, source_clauses_json, source_pages_json, sort_order) VALUES (` +
          [
            q(lessonId),
            q(courseId),
            q(lesson.slug),
            q(lesson.title),
            q(body),
            n(body ? Math.max(5, Math.min(30, Math.round(body.split(/\s+/).length / 180))) : 10),
            q(JSON.stringify(clauseIds)),
            q(JSON.stringify(pages)),
            n(lessonOrder++)
          ].join(", ") +
          ");"
      );
    }
  }
}

log(`catalog: ${curriculum.certifications.length} certifications, ${lessonRows.length} lessons`);

// =============================================================================
// 2. Questions — deterministic, from real corpus values
// =============================================================================
const questionsSql = [];

const UNIT_KINDS = new Set(["mm", "m", "m2", "feet", "in", "days", "%"]);
// collect real values per unit for plausible distractors (never fabricated)
const valuePoolByUnit = new Map();
function pool(unit, value) {
  if (!valuePoolByUnit.has(unit)) valuePoolByUnit.set(unit, new Set());
  valuePoolByUnit.get(unit).add(value);
}

const requirements = readJsonl(P("requirements/requirements.jsonl"));
log(`requirements: ${requirements.length}`);

// First pass: build the pool of real numeric values per unit.
for (const r of requirements) {
  for (const p of r.parameters ?? []) {
    if (p.parameter === "measurement" && p.value != null && UNIT_KINDS.has(p.unit)) {
      pool(p.unit, p.value);
    }
  }
}

// Deliberately-spread distractors: prefer corpus values in distinct distance
// bands from the correct answer so options are not near-identical. Falls back to
// multiplicative nudges only when the corpus lacks a band.
function pickDistractors(unit, correct) {
  const out = [];
  const taken = new Set([correct]);
  const add = (v) => {
    if (out.length >= 3 || taken.has(v)) return;
    taken.add(v);
    out.push(v);
  };
  // Bands as ratios of the correct value: clearly-wrong magnitudes.
  const bands = [0.5, 1.5, 2, 0.25, 3, 0.75, 1.25];
  const candidates = [...(valuePoolByUnit.get(unit) || new Set())].filter((v) => v !== correct);
  for (const ratio of bands) {
    if (out.length >= 3) break;
    const target = correct * ratio;
    let best = null;
    let bestD = Infinity;
    for (const v of candidates) {
      if (taken.has(v)) continue;
      const d = Math.abs(v - target);
      // Require at least 10% separation from the correct value to avoid look-alikes.
      if (Math.abs(v - correct) / Math.abs(correct || 1) < 0.1) continue;
      if (d < bestD) { bestD = d; best = v; }
    }
    if (best != null) add(best);
  }
  const nudges = [correct * 0.5, correct * 1.5, correct * 2].map((x) => Math.round(x * 100) / 100);
  for (const v of nudges) add(v);
  return out.slice(0, 3);
}

// Build a specific, human-readable question that asks for the stated value
// WITHOUT revealing it (the correct value is one of the options).
function thresholdPrompt(r, param) {
  // Prefer a clean sentence from source_text; fall back to the param context.
  const candidates = [r.source_text, param.context]
    .map((s) => (s || "").replace(/\s+/g, " ").trim())
    .filter((s) => s.length >= 12);
  let subject = candidates[0] || `the requirement in Clause ${r.clause}`;
  // Blank out numeric values (and any trailing parenthetical) so the answer isn't shown.
  subject = subject
    .replace(/[\d.,]+\s*(mm|m2|m|feet|foot|ft|inches|inch|in|days?|%|square feet)/gi, "______")
    .replace(/______(\s*\([^)]*\))?/g, "______")
    .replace(/\s+/g, " ")
    .trim();
  // Re-anchor to the first "______" so the sentence reads from a whole word.
  const blankAt = subject.indexOf("______");
  if (blankAt > 60) subject = subject.slice(blankAt - 60).replace(/^\S*\s/, "");
  if (subject.length > 220) subject = subject.slice(0, 220).replace(/\s+\S*$/, "") + "…";
  if (subject.length < 12) subject = `the requirement in Clause ${r.clause}`;
  return `GS 1207:2018 Part ${r.part} (Clause ${r.clause}): “…${subject}…” — what value is stated?`;
}

let thresholdCount = 0;
for (const r of requirements) {
  const isExtracted = r.verification_status === "extracted" && (r.confidence ?? 0) >= 0.9;
  for (const p of r.parameters ?? []) {
    if (p.parameter !== "measurement" || p.value == null || !UNIT_KINDS.has(p.unit)) continue;
    const correct = p.value;
    const unit = p.unit;
    const distractors = pickDistractors(unit, correct);
    if (distractors.length < 3) continue;

    const options = [correct, ...distractors].map((v) => `${v} ${unit}`);
    // deterministic shuffle: rotate by hash of requirement id
    const rot = parseInt(createHash("sha1").update(r.requirement_id + unit).digest("hex").slice(0, 2), 16) % 4;
    const rotated = options.slice(rot).concat(options.slice(0, rot));
    const correctIndex = rotated.indexOf(`${correct} ${unit}`);

    const prompt = thresholdPrompt(r, p);
    const explanation =
      `Clause ${r.clause} (${r.clause_id}, page ${r.page_start}): ` +
      (r.source_text || "").slice(0, 400);

    questionsSql.push(
      `INSERT OR REPLACE INTO academy_questions (id, course_id, lesson_id, kind, part_no, prompt, options_json, correct_index, explanation, difficulty, clause_id, requirement_id, page, content_hash, verification_status, is_exam_eligible) VALUES (` +
        [
          q(id("q", r.requirement_id, unit)),
          "NULL",
          "NULL",
          q("threshold"),
          n(r.part),
          q(prompt),
          q(JSON.stringify(rotated)),
          n(correctIndex),
          q(explanation),
          q(isExtracted ? "standard" : "study"),
          q(r.clause_id),
          q(r.requirement_id),
          n(r.page_start),
          q(r.content_hash),
          q(r.verification_status),
          isExtracted ? 1 : 0
        ].join(", ") +
        ");"
    );
    thresholdCount++;
    if (thresholdCount >= 4000) break; // keep the seed file sane; enough for all tracks
  }
  if (thresholdCount >= 4000) break;
}
log(`questions: ${thresholdCount} threshold items`);

// --- definition MCQs from the glossary ---------------------------------------
const definitions = readJsonl(P("definitions/definitions.jsonl"));
const byFirstWord = new Map();
for (const d of definitions) {
  const t = String(d.term || "").trim();
  if (t.length < 3 || t.length > 40) continue;
  const key = t[0].toUpperCase();
  if (!byFirstWord.has(key)) byFirstWord.set(key, []);
  byFirstWord.get(key).push(d);
}
let defCount = 0;
for (const d of definitions) {
  const t = String(d.term || "").trim();
  const def = String(d.definition || "").trim();
  if (t.length < 3 || t.length > 40 || def.length < 20) continue;
  const siblings = byFirstWord.get(t[0].toUpperCase()) || [];
  const others = siblings.filter((x) => x.term !== t).slice(0, 3);
  if (others.length < 3) continue;
  const options = [t, ...others.map((o) => o.term)];
  options.sort((a, b) => a.localeCompare(b));
  const correctIndex = options.indexOf(t);
  questionsSql.push(
    `INSERT OR REPLACE INTO academy_questions (id, course_id, lesson_id, kind, part_no, prompt, options_json, correct_index, explanation, difficulty, clause_id, requirement_id, page, content_hash, verification_status, is_exam_eligible) VALUES (` +
      [
        q(id("qdef", t)),
        "NULL",
        "NULL",
        q("definition"),
        n(d.source_part ?? 2),
        q(`Which term is defined as: "${def.slice(0, 240)}"`),
        q(JSON.stringify(options)),
        n(correctIndex),
        q(`Part 2 (${d.source_clause}, page ${d.page}): ${def.slice(0, 300)}`),
        q("standard"),
        q(d.source_clause),
        "NULL",
        n(d.page),
        q(d.content_hash),
        q("extracted"),
        1
      ].join(", ") +
      ");"
  );
  defCount++;
  if (defCount >= 600) break;
}
log(`questions: ${defCount} definition items`);

// =============================================================================
// 3. Emit
// =============================================================================
const header = [
  "-- GHBC Academy seed — generated by scripts/build-academy.mjs",
  `-- corpus: ${CORPUS}`,
  `-- generated: ${new Date().toISOString()}`,
  `-- certifications=${curriculum.certifications.length} lessons=${lessonRows.length} questions=${thresholdCount + defCount}`,
  "PRAGMA foreign_keys = ON;",
  "BEGIN TRANSACTION;"
].join("\n");

const footer = "COMMIT;";
const sql = [header, "", ...catalogSql, "", ...questionsSql, "", footer, ""].join("\n");

if (CHECK_ONLY) {
  log(`check only — would write ${catalogSql.length + questionsSql.length} statements`);
} else {
  fs.mkdirSync(path.dirname(OUT_PATH), { recursive: true });
  fs.writeFileSync(OUT_PATH, sql, "utf8");
  log(`wrote ${OUT_PATH} (${(sql.length / 1024).toFixed(1)} KB, ${catalogSql.length + questionsSql.length} statements)`);
}
