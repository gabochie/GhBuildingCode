import { existsSync, mkdirSync, readdirSync, readFileSync, statSync, writeFileSync } from "node:fs";
import { join, resolve, sep } from "node:path";

const root = process.cwd();
const nextDir = resolve(root, ".next");
const publicDir = resolve(root, "public");

if (!existsSync(nextDir)) {
  console.warn("[build-sw] .next not found — run `next build` first. Skipping.");
  process.exit(0);
}

const buildIdFile = join(nextDir, "BUILD_ID");
const buildId = existsSync(buildIdFile) ? readFileSync(buildIdFile, "utf8").trim() : "dev";

const isDev = buildId === "development";

function walk(dir, base) {
  const out = [];
  for (const entry of readdirSync(dir)) {
    const p = join(dir, entry);
    if (statSync(p).isDirectory()) {
      out.push(...walk(p, base));
    } else {
      out.push("/_next/static" + "/" + p.replace(base, "").split(sep).join("/").replace(/^\/+|\/+$/g, ""));
    }
  }
  return out;
}

const staticDir = join(nextDir, "static");
const staticUrls = isDev ? [] : existsSync(staticDir) ? walk(staticDir, staticDir) : [];

const PRECACHE = isDev ? [] : ["/offline", ...staticUrls];
const VERSION = "v" + buildId;
const CACHE = "ghbc-" + VERSION;

const sw = `/*! GHBC service worker — generated by scripts/build-sw.mjs (build ${buildId}). Do not edit. */
const VERSION = ${JSON.stringify(VERSION)};
const CACHE = ${JSON.stringify(CACHE)};
const PRECACHE = ${JSON.stringify(PRECACHE)};

self.addEventListener("install", (event) => {
  event.waitUntil(
    caches
      .open(CACHE)
      .then((cache) => cache.addAll(PRECACHE))
      .then(() => self.skipWaiting())
      .catch((err) => console.error("[sw] precache failed:", err))
  );
});

self.addEventListener("activate", (event) => {
  event.waitUntil(
    caches
      .keys()
      .then((keys) => Promise.all(keys.filter((k) => k !== CACHE).map((k) => caches.delete(k))))
      .then(() => self.clients.claim())
  );
});

self.addEventListener("fetch", (event) => {
  const req = event.request;
  const url = new URL(req.url);

  if (req.method !== "GET" || url.origin !== self.location.origin) return;

  // Immutable hashed assets — cache-first.
  if (url.pathname.startsWith("/_next/static/")) {
    event.respondWith(
      caches.match(req).then(
        (hit) =>
          hit ||
          fetch(req).then((res) => {
            const copy = res.clone();
            caches.open(CACHE).then((cache) => cache.put(req, copy));
            return res;
          })
      )
    );
    return;
  }

  // Navigations — never cache HTML (auth/user-specific), network first,
  // fall back to the cached offline page.
  if (req.mode === "navigate") {
    event.respondWith(
      fetch(req).catch(() =>
        caches.match("/offline").then((hit) => hit || Response.error())
      )
    );
    return;
  }

  // Everything else (RSC/API/scripts/images) — network only.
  return;
});
`;

if (!existsSync(publicDir)) mkdirSync(publicDir, { recursive: true });
const out = resolve(publicDir, "sw.js");
writeFileSync(out, sw);
console.log(
  `[build-sw] wrote ${join("public", "sw.js")} (${PRECACHE.length} precache entries, build ${buildId}).`
);
console.log(`  cached: /offline + ${staticUrls.length} /_next/static/* assets`);