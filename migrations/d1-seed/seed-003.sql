## How the Code Is Structured (and Why It Matters for Your Workflow)

GS 1207:2018 is not a single prescriptive checklist. It is a layered system of performance requirements, deemed-to-satisfy provisions, and alternative solutions. Understanding this structure is essential for efficient compliance.

### The 38 Parts: A Framework, Not a List

The Code''s 38 parts are organised by building system and function:

- Parts 1–2: General provisions and occupancy classifications. Part 2 is the starting point for every project — your occupancy group determines nearly every downstream requirement.
- Parts 3–5: Structural design, including dead loads, live loads, wind loads, and seismic provisions.
- Parts 6–8: Fire safety, means of egress, and fire-resistance ratings.
- Part 9: Fire detection, alarm, and suppression systems.
- Part 10: Accessibility for persons with disabilities.
- Parts 11–12: Thermal performance, energy efficiency, and water conservation.
- Parts 13–38: Site works, drainage, plumbing, electrical installations, lifts, and specialised provisions.

Knowing which parts apply to your building type, occupancy classification, and site conditions is the difference between a smooth permit process and months of costly revisions.

### Performance Requirements vs. Deemed-to-Satisfy

The Code offers two paths to compliance:

1. Performance requirements: Meet the stated performance objective (e.g., "the structure shall resist the specified loads without failure"). This path allows flexibility but requires engineering justification.
2. Deemed-to-satisfy provisions: Follow the specific prescriptive requirements (e.g., minimum fire-resistance ratings, maximum travel distances). This path is more straightforward but less flexible.

Most architects work within the deemed-to-satisfy provisions. Understanding when you can use alternative solutions — and how to document them — is a differentiator.

